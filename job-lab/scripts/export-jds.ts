/**
 * npm run export-jds — write the full job descriptions already in your local
 * database to ../context-library/job-descriptions.md. FREE. No scraping, no API
 * calls, nothing leaves this machine.
 *
 *   npm run export-jds                       the newest 120 jobs
 *   npm run export-jds -- --days-back 14     only jobs posted in the last 2 weeks
 *   npm run export-jds -- --limit 60
 *   npm run export-jds -- --help
 *
 * npm run export writes titles, companies and scores, never the JD text. Keyword
 * work (LinkedIn About, experience, resume) needs the text, and Claude must never
 * read jobs.db directly, so this is the readable hand-off. Hidden jobs and
 * duplicates are skipped. Each description is whitespace-collapsed and capped so
 * the file stays small enough to read in one pass.
 */
import "dotenv/config";
import fs from "node:fs";
import path from "node:path";
import { db } from "../src/db";
import { main, type CommandSpec } from "../src/args";
import { contextLibrary, parse, plural } from "./_lib";

const MAX_LIMIT = 300;
const MAX_JD_CHARS = 6000;

const SPEC: CommandSpec = {
  command: "npm run export-jds",
  summary:
    "Write the full job descriptions in your local database to context-library/job-descriptions.md. " +
    "Free, offline: it calls nothing.",
  flags: [
    {
      name: "limit",
      type: "number",
      desc: `how many jobs to include (${MAX_LIMIT} at most)`,
      placeholder: "<number>",
      default: 120,
    },
    {
      name: "days-back",
      type: "number",
      desc: "only jobs posted in the last N days",
      placeholder: "<number>",
    },
    { name: "out", desc: "folder to write to instead of context-library", placeholder: "<folder>" },
  ],
  examples: ["npm run export-jds -- --days-back 14", "npm run export-jds -- --limit 60"],
};

type Row = {
  company: string;
  role: string;
  location: string | null;
  posted_at: string | null;
  first_seen: string | null;
  salary: string | null;
  url: string | null;
  description: string | null;
};

if (require.main === module) {
  const o = parse(SPEC);

  void main(async () => {
    const limit = Math.max(1, Math.min(MAX_LIMIT, Math.floor(o.num("limit", 120))));
    const daysBack = o.num("days-back", NaN);

    const where = [
      "COALESCE(status, '') != 'hidden'",
      "duplicate_of IS NULL",
      "description IS NOT NULL",
      "TRIM(description) != ''",
    ];
    const params: unknown[] = [];
    if (Number.isFinite(daysBack)) {
      where.push("COALESCE(posted_at, first_seen) >= ?");
      params.push(new Date(Date.now() - daysBack * 86_400_000).toISOString());
    }

    const rows = db()
      .prepare(
        `SELECT company, role, location, posted_at, first_seen, salary, url, description
           FROM jobs WHERE ${where.join(" AND ")}
          ORDER BY COALESCE(posted_at, first_seen) DESC
          LIMIT ?`,
      )
      .all(...params, limit) as Row[];

    const dash = "—";
    const L: string[] = [
      "# Job Descriptions",
      "",
      `Generated: ${new Date().toISOString().slice(0, 10)}`,
      `Jobs: ${rows.length}${Number.isFinite(daysBack) ? ` (posted in the last ${daysBack} days)` : ""}`,
      "",
      "Auto-generated by `npm run export-jds`. Do not hand-edit — it is overwritten on every run.",
      "",
    ];
    if (!rows.length) {
      L.push("No job descriptions in the database yet. Run `npm run find-jobs` first.");
    }
    rows.forEach((r, i) => {
      const jd = r.description!.replace(/\s+/g, " ").trim();
      L.push(
        `## ${i + 1}. ${r.role} — ${r.company}`,
        "",
        `- Location: ${r.location || dash}`,
        `- Posted: ${(r.posted_at || r.first_seen || dash).slice(0, 10)}`,
        `- Salary: ${r.salary || dash}`,
        `- URL: ${r.url || dash}`,
        "",
        jd.length > MAX_JD_CHARS ? jd.slice(0, MAX_JD_CHARS) + " …[truncated]" : jd,
        "",
      );
    });

    const dir = o.str("out") ?? contextLibrary();
    const file = path.join(dir, "job-descriptions.md");
    fs.writeFileSync(file, L.join("\n"));
    console.log(`Wrote ${plural(rows.length, "job description")} to ${file}`);
  });
}
